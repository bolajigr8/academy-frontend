export function project(lng: number, lat: number): { x: number; y: number } {
  return {
    x: Math.round((lng - BOUNDS.lngMin) * K * PX * 10) / 10,
    y: Math.round((BOUNDS.latMax - lat) * PX * 10) / 10,
  }
}

/* Ray casting in lng/lat space. */
export function pointInPolygon(
  lng: number,
  lat: number,
  poly: number[][]
): boolean {
  let inside = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const xi = poly[i][0],
      yi = poly[i][1],
      xj = poly[j][0],
      yj = poly[j][1]
    if (
      yi > lat !== yj > lat &&
      lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    )
      inside = !inside
  }
  return inside
}
export function onLand(lng: number, lat: number): boolean {
  return Object.keys(LAND).some(function (k) {
    return pointInPolygon(lng, lat, LAND[k])
  })
}

/* Dot matrix: sample a regular grid in projected space. */
export function landDots(step?: number): number[][] {
  const s = step || 9
  const dots: number[][] = []
  for (let y = s / 2; y < HEIGHT; y += s) {
    const row = Math.round(y / s)
    for (let x = (row % 2 ? s / 2 : 0) + s / 2; x < WIDTH; x += s) {
      const lng = x / (K * PX) + BOUNDS.lngMin
      const lat = BOUNDS.latMax - y / PX
      if (onLand(lng, lat))
        dots.push([Math.round(x * 10) / 10, Math.round(y * 10) / 10])
    }
  }
  return dots
}
